import crypto from 'crypto';
import QRCode from 'qrcode';
import CONFIG from '../config.js';
import { prisma } from './db.js';

export interface QrPayload {
  hubId: string;
  hubCode: string;
  nonce: string;
  expiresAt: number; // Unix timestamp in ms
  signature: string;
}

export interface QrVerificationResult {
  isValid: boolean;
  errorCode?: string;
  errorMessage?: string;
  tokenId?: string;
  hubId?: string;
  hubCode?: string;
}

/**
 * Sign payload parameters with HMAC-SHA256
 */
export function generateQrSignature(
  hubId: string,
  nonce: string,
  expiresAt: number
): string {
  const data = `${hubId}:${nonce}:${expiresAt}`;
  return crypto
    .createHmac(CONFIG.QR.ALGORITHM, CONFIG.SECURITY.HMAC_QR_SECRET)
    .update(data)
    .digest('hex');
}

/**
 * Generate a dynamic, signed, short-lived QR code for a given hub
 */
export async function generateDynamicHubQr(
  hubId: string,
  hubCode: string,
  validitySeconds: number = CONFIG.QR.VALIDITY_SECONDS
): Promise<{
  qrPayloadString: string;
  qrDataUrl: string;
  expiresAt: Date;
  secondsRemaining: number;
  nonce: string;
  tokenRecordId: string;
}> {
  // Validate validity seconds within bounds (30 - 60 seconds)
  const safeValidity = Math.max(
    CONFIG.QR.MIN_VALIDITY_SECONDS,
    Math.min(CONFIG.QR.MAX_VALIDITY_SECONDS, validitySeconds)
  );

  const nonce = crypto.randomBytes(16).toString('hex');
  const now = Date.now();
  const expiresAtMs = now + safeValidity * 1000;
  const expiresAtDate = new Date(expiresAtMs);

  const signature = generateQrSignature(hubId, nonce, expiresAtMs);

  const payload: QrPayload = {
    hubId,
    hubCode,
    nonce,
    expiresAt: expiresAtMs,
    signature,
  };

  const payloadString = JSON.stringify(payload);

  // Store in database with index for rapid validation
  const tokenRecord = await prisma.hubQrToken.create({
    data: {
      hubId,
      token: payloadString,
      nonce,
      signature,
      expiresAt: expiresAtDate,
      isConsumed: false,
    },
  });

  // Generate QR code Data URL for rendering on Hub screen
  const qrDataUrl = await QRCode.toDataURL(payloadString, {
    errorCorrectionLevel: 'H',
    margin: 2,
    scale: 8,
    color: {
      dark: '#14243A', // Primary enterprise navy
      light: '#FFFFFF',
    },
  });

  return {
    qrPayloadString: payloadString,
    qrDataUrl,
    expiresAt: expiresAtDate,
    secondsRemaining: safeValidity,
    nonce,
    tokenRecordId: tokenRecord.id,
  };
}

/**
 * Server-side cryptographic and database validation of a scanned QR payload
 */
export async function verifyScannedQrPayload(
  payloadString: string,
  expectedHubId?: string,
  employeeId?: string
): Promise<QrVerificationResult> {
  // 1. Parse JSON payload
  let payload: QrPayload;
  try {
    payload = JSON.parse(payloadString);
  } catch {
    return {
      isValid: false,
      errorCode: 'MALFORMED_PAYLOAD',
      errorMessage: 'The scanned QR code is malformed or invalid.',
    };
  }

  const { hubId, nonce, expiresAt, signature, hubCode } = payload;
  if (!hubId || !nonce || !expiresAt || !signature) {
    return {
      isValid: false,
      errorCode: 'MISSING_PAYLOAD_FIELDS',
      errorMessage: 'Scanned QR token is missing essential cryptographic parameters.',
    };
  }

  // 2. Hub ID constraint check if expected
  if (expectedHubId && hubId !== expectedHubId) {
    return {
      isValid: false,
      errorCode: 'HUB_MISMATCH',
      errorMessage: `QR token was generated by hub ${hubCode || hubId}, not the target hub.`,
    };
  }

  // 3. Cryptographic Signature Verification
  const expectedSignature = generateQrSignature(hubId, nonce, expiresAt);
  const isValidSignature = crypto.timingSafeEqual(
    Buffer.from(signature, 'hex'),
    Buffer.from(expectedSignature, 'hex')
  );

  if (!isValidSignature) {
    return {
      isValid: false,
      errorCode: 'SIGNATURE_INVALID',
      errorMessage: 'Cryptographic signature verification failed. QR token is forged or tampered.',
    };
  }

  // 4. Server-side Expiration Check (with small grace allowance for network transit)
  const nowMs = Date.now();
  const gracePeriodMs = CONFIG.QR.CLOCK_DRIFT_GRACE_SECONDS * 1000;
  if (nowMs > expiresAt + gracePeriodMs) {
    return {
      isValid: false,
      errorCode: 'TOKEN_EXPIRED',
      errorMessage: 'QR code has expired. A fresh dynamic token must be scanned.',
    };
  }

  // 5. Database Replay & Single-Use Check
  const tokenRecord = await prisma.hubQrToken.findUnique({
    where: { nonce },
    include: { hub: true },
  });

  if (!tokenRecord) {
    return {
      isValid: false,
      errorCode: 'TOKEN_NOT_REGISTERED',
      errorMessage: 'QR token was not recognized in server records.',
    };
  }

  if (tokenRecord.isConsumed) {
    return {
      isValid: false,
      errorCode: 'TOKEN_ALREADY_USED',
      errorMessage: 'Replay detected! This dynamic QR token has already been consumed for attendance.',
    };
  }

  if (!tokenRecord.hub.isActive) {
    return {
      isValid: false,
      errorCode: 'HUB_INACTIVE',
      errorMessage: 'The hub associated with this QR token is currently marked inactive.',
    };
  }

  // 6. Mark token as consumed atomically if single-use is enforced
  if (CONFIG.QR.SINGLE_USE_ENFORCED) {
    await prisma.hubQrToken.update({
      where: { id: tokenRecord.id },
      data: {
        isConsumed: true,
        consumedAt: new Date(),
        consumedBy: employeeId || 'ANONYMOUS',
      },
    });
  }

  return {
    isValid: true,
    tokenId: tokenRecord.id,
    hubId: tokenRecord.hubId,
    hubCode: tokenRecord.hub.hubCode,
  };
}
